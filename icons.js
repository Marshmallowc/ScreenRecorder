/**
 * Injects an SVG icon into a targeted DOM element.
 * @param {HTMLElement} element - The target DOM element.
 * @param {string} iconName - The name of the icon in CapuraIcons.
 * @param {string} [className] - Optional CSS classes to add to the SVG element.
 */
CapuraIcons.inject = function(element, iconName, className = '') {
  if (!element || !CapuraIcons[iconName]) return;
  
  // Parse the raw SVG string
  const parser = new DOMParser();
  const doc = parser.parseFromString(CapuraIcons[iconName], 'image/svg+xml');
  const svg = doc.querySelector('svg');
  
  if (svg) {
    if (className) {
      // Handle multiple classes split by space
      className.split(' ').filter(c => c.trim()).forEach(c => svg.classList.add(c));
    }
    // Clear and append
    element.innerHTML = '';
    element.appendChild(svg);
  }
};

// Also listen for auto-injections via data-attributes: data-capura-icon="iconName"
document.addEventListener('DOMContentLoaded', () => {
  const elements = document.querySelectorAll('[data-capura-icon]');
  elements.forEach(element => {
    const iconName = element.getAttribute('data-capura-icon');
    const classes = element.getAttribute('data-capura-class') || '';
    CapuraIcons.inject(element, iconName, classes);
  });
});
